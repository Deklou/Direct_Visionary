fn key_hash(name: &str) -> Option<u64> {
    if let Some(hex) = name.strip_prefix("0x") {
        return u64::from_str_radix(hex, 16).ok().filter(|h| *h <= 0xffffffffff);
    }
    // skyline-smash names fields with unresolved PRC hashes as x<10 hex digits>.
    if let Some(hex) = name.strip_prefix('x') {
        if hex.len() == 10 && hex.bytes().all(|b| b.is_ascii_hexdigit()) {
            return u64::from_str_radix(hex, 16).ok();
        }
    }
    Some(smash::hash40(name) & 0xffffffffff)
}

static BY_HASH: LazyLock<HashMap<u64, &'static FieldSpec>> = LazyLock::new(|| {
    FIELDS.iter().filter_map(|field| key_hash(field.name).map(|hash| (hash, field))).collect()
});

pub fn lookup(key: &str) -> Option<&'static FieldSpec> {
    BY_HASH.get(&key_hash(key)?).copied()
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn fields_do_not_overlap_or_escape_the_row() {
        assert_eq!(FIELDS.len(), 368);
        let mut bytes = [false; 0x628];
        for field in FIELDS {
            let width = match field.kind { ValueKind::Hash => 8, ValueKind::Bool => 1, _ => 4 };
            assert!(field.offset + width <= bytes.len(), "{}", field.name);
            for used in &mut bytes[field.offset..field.offset + width] {
                assert!(!*used, "overlap: {}", field.name);
                *used = true;
            }
        }
        assert_eq!(lookup("weight").unwrap().offset, 0x80);
        assert_eq!(lookup("air_speed_x_stable").unwrap().offset, 0x60);
        assert!(lookup("fighter_kind").is_none());
    }
}
